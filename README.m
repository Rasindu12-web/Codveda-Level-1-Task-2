💻 GitHub Repository: https://github.com/Rasindu12-web/Codveda-Level-1-Task-2

 Key Features

- Premium responsive registration interface
- Real-time input validation
- Full name, email, and phone number validation
- Password strength indicator
- Password visibility toggle
- Confirm password matching
- Dynamic error and success messages
- Mobile-friendly layout
- Form submission without page reload

Technologies Used

- HTML5 – Form structure and semantic elements
- CSS3 – Responsive design, animations, and visual styling
- JavaScript (ES6+) – DOM manipulation, event handling, and validation

