 Codveda Level 1 – Task 2 | Interactive Form Validation

 Project Overview

A modern, responsive registration form developed as part of my Front-End Development Internship at Codveda Technologies.

This project demonstrates interactive form validation using HTML5, CSS3, and Vanilla JavaScript, with a focus on user experience, responsive design, and real-time feedback.

 Live Demo

