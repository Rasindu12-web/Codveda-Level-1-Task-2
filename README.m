 How to Run Locally

1. Download or clone the repository.
2. Open the project folder in Visual Studio Code.
3. Open `index.html` using Live Server.
4. Test the interactive form validation.

 Validation Demonstration

The form checks required fields, email formatting, Sri Lankan mobile number formatting, password requirements, and password confirmation.

When valid information is entered, the application displays a success message without refreshing the page.

Note: This project is a front-end demonstration only. No real user account is created, and form information is not submitted to a backend server.

